import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { compileFlint, type FlintArtifact } from "@mission-platform/flint";

import {
  decodeUtf8,
  encodeUtf8,
  hashArtifactBytes,
  normalizeBenchmarkOutput,
  readGuestBytes,
  validateManifestExports,
  validateWasmArtifact,
  writeGuestBytes,
} from "../abi.ts";

import type {
  BenchmarkInput,
  BenchmarkOutput,
  BuildArtifact,
  FlintMode,
  InitializedAdapter,
  RuntimeAdapter,
} from "../contracts.ts";

const COMPILER_VERSION = "benchmark-flint-v1";
const SOURCE_FILE = "benchmark/implementations/flint/kernels.flint";

const REQUIRED_EXPORTS = [
  "arithmetic_reduce",
  "string_transform",
  "dataset_scan",
  "memory",
  "fws_alloc",
  "fws_dealloc",
  "fws_realloc",
  "fws_reset",
] as const;

/**
 * Asserts that an object value is defined and non-null, throwing an Error otherwise.
 *
 * @param value - Value to assert.
 * @param failureMessage - Diagnostic error message.
 * @returns The asserted defined value.
 * @throws {Error} When value is undefined or null.
 */
function assertDefined<T extends object>(
  value: T | undefined | null,
  failureMessage: string,
): T {
  if (value === undefined || value === null) {
    throw new Error(failureMessage);
  }
  return value;
}

/**
 * Reads the raw Flint kernel source file from disk.
 *
 * @returns UTF-8 content of the benchmark kernels file.
 */
function resolveSource(): string {
  const currentDirectory = path.dirname(fileURLToPath(import.meta.url));
  const filePath = path.resolve(
    currentDirectory,
    "../../implementations/flint/kernels.flint",
  );
  return readFileSync(filePath, "utf8");
}

/**
 * Raw WebAssembly exports matching the native Flint kernel ABI.
 */
interface FlintExports {
  readonly arithmetic_reduce: (
    n: number,
    multiplier: number,
    offset: number,
    seed: number,
  ) => number;
  readonly string_transform: (
    valuePointer: number,
    valueLength: number,
    prefixPointer: number,
    prefixLength: number,
    suffixPointer: number,
    suffixLength: number,
    repeat: number,
  ) => readonly [number, number];
  readonly dataset_scan: (
    pointer: number,
    length: number,
    threshold: number,
  ) => number;
  readonly memory: WebAssembly.Memory;
  readonly fws_alloc: (size: number) => number;
  readonly fws_dealloc: (pointer: number, size: number) => void;
  readonly fws_realloc: (
    pointer: number,
    oldSize: number,
    newSize: number,
  ) => number;
  readonly fws_reset: () => void;
}

/**
 * Higher-level ESM exports generated by the Flint compiler.
 */
interface GeneratedFlintExports {
  readonly arithmetic_reduce: FlintExports["arithmetic_reduce"];
  readonly string_transform: (
    value: string,
    prefix: string,
    suffix: string,
    repeat: number,
  ) => string;
  readonly dataset_scan: (
    bytes: readonly [pointer: number, length: number],
    threshold: number,
  ) => number;
  readonly memory: WebAssembly.Memory;
  readonly fws_alloc: FlintExports["fws_alloc"];
  readonly fws_dealloc: FlintExports["fws_dealloc"];
  readonly fws_realloc: FlintExports["fws_realloc"];
  readonly fws_reset: FlintExports["fws_reset"];
}

/**
 * ESM module interface produced by compiler code generation.
 */
interface GeneratedFlintModule {
  readonly load: () => Promise<GeneratedFlintExports>;
  readonly loadSync: () => GeneratedFlintExports;
}

/**
 * Type guard verifying that WebAssembly exports satisfy the required Flint ABI.
 *
 * @param value - Untyped WebAssembly exports dictionary.
 * @returns True if value satisfies all FlintExports requirements.
 */
function isFlintExports(
  value: WebAssembly.Exports,
): value is WebAssembly.Exports & FlintExports {
  return (
    typeof value.arithmetic_reduce === "function" &&
    typeof value.string_transform === "function" &&
    typeof value.dataset_scan === "function" &&
    value.memory instanceof WebAssembly.Memory &&
    typeof value.fws_alloc === "function" &&
    typeof value.fws_dealloc === "function" &&
    typeof value.fws_realloc === "function" &&
    typeof value.fws_reset === "function"
  );
}

/**
 * Safely validates and casts raw WebAssembly exports to the FlintExports interface.
 *
 * @param value - Exported members from a WebAssembly instance.
 * @returns Validated FlintExports contract.
 * @throws {TypeError} If any required exports are missing or invalid.
 */
function asExports(value: WebAssembly.Exports): FlintExports {
  if (!isFlintExports(value)) {
    throw new TypeError(
      "Flint WASM module does not satisfy the native benchmark ABI.",
    );
  }
  return value;
}

/**
 * Validates the completeness and integrity of a compiled Flint artifact.
 *
 * @param artifact - Compiler output artifact.
 * @returns Array of validated WebAssembly export names.
 * @throws {Error} If bytecode, manifest, or hashes do not validate.
 */
export function validateFlintWasmArtifact(
  artifact: FlintArtifact,
): readonly string[] {
  if (artifact.wasm === undefined || artifact.manifest === undefined) {
    throw new Error("Flint artifact is incomplete.");
  }
  const exports = validateWasmArtifact(artifact.wasm, REQUIRED_EXPORTS);
  validateManifestExports(artifact.manifest, [
    "arithmetic_reduce",
    "string_transform",
    "dataset_scan",
  ]);
  if (artifact.contentHash !== hashArtifactBytes(artifact.wasm)) {
    throw new Error(
      "Flint artifact content hash does not match its WASM bytes.",
    );
  }
  if (!artifact.esmSource.includes("loadSync")) {
    throw new Error("Flint artifact is missing its generated ESM loader.");
  }
  return exports;
}

/**
 * Loader mode for Flint WebAssembly adapters: raw WebAssembly or compiler-generated ESM.
 */
type FwsWasmLoader = "raw" | "generated";

/**
 * Memory pointer and length slice for allocated guest buffers.
 */
interface MemoryRange {
  readonly pointer: number;
  readonly length: number;
}

/**
 * Deallocates unique memory slices from guest WebAssembly memory.
 *
 * @param exports - Module exports providing the deallocation ABI.
 * @param ranges - Slices to deallocate.
 */
function releaseRanges(
  exports: Pick<FlintExports, "fws_dealloc">,
  ranges: readonly (MemoryRange | undefined)[],
): void {
  const released = new Set<string>();
  for (const range of ranges) {
    if (range === undefined) continue;
    const key = `${range.pointer}:${range.length}`;
    if (released.has(key)) continue;
    released.add(key);
    exports.fws_dealloc(range.pointer, range.length);
  }
}

/**
 * Wraps an execution in the reset ABI lifecycle, guaranteeing reset execution upon completion.
 *
 * @param exports - Module exports providing the reset ABI.
 * @param operation - Benchmark operation closure.
 * @returns Result of the operation.
 * @throws {Error} Rethrows any operation error or reset failure.
 */
function withReset<T extends BenchmarkOutput | number | string | void>(
  exports: Pick<FlintExports, "fws_reset">,
  operation: () => T,
): T {
  exports.fws_reset();
  let operationFailed = false;
  try {
    return operation();
  } catch (error) {
    operationFailed = true;
    throw error;
  } finally {
    try {
      exports.fws_reset();
    } catch (resetError) {
      if (!operationFailed) throw resetError;
    }
  }
}

/**
 * In-memory compiled state for an Flint WebAssembly adapter instance.
 */
interface CompiledWasmState {
  readonly artifact: FlintArtifact;
  readonly wasmBytes: Uint8Array;
  readonly module: WebAssembly.Module;
  readonly generatedModuleUrl: string;
}

/**
 * Result of instantiating the WebAssembly module or ESM glue.
 */
interface WasmInstantiationResult {
  readonly preparedExports?: FlintExports;
  readonly generatedExports?: GeneratedFlintExports;
}

/**
 * Computes the canonical artifact identifier based on loader and bounds configuration.
 *
 * @param modeOverride - Optional explicit mode override.
 * @param generated - Whether using generated ESM loader.
 * @returns Stable artifact string identifier.
 */
function resolveArtifactId(
  modeOverride: FlintMode | undefined,
  generated: boolean,
): string {
  if (modeOverride === "wasm-excluded-bounds") {
    return "flint-wasm-excluded-bounds";
  }
  return generated ? "flint-wasm-generated" : "fws-wasm";
}

/**
 * Constructs the benchmark build artifact descriptor for a compiled Flint WebAssembly module.
 *
 * @param artifactId - Artifact identifier.
 * @param flintMode - Target Flint mode.
 * @param boundsChecks - Bounds checking profile.
 * @param generated - Whether using generated ESM loader.
 * @param artifact - Raw compiler artifact.
 * @param generatedSource - Encoded ESM source bytes.
 * @param generatedPath - Local filesystem path where WASM is written.
 * @param generatedModulePath - Local filesystem path where ESM is written.
 * @returns Benchmark build artifact metadata.
 */
function buildWasmArtifactDescriptor(
  artifactId: string,
  flintMode: FlintMode,
  boundsChecks: "runtime" | "excluded-by-profile",
  generated: boolean,
  artifact: FlintArtifact,
  generatedSource: Uint8Array,
  generatedPath: string,
  generatedModulePath: string,
): BuildArtifact {
  const wasmByteLength = assertDefined(
    artifact.wasm,
    "Missing WASM bytes in artifact.",
  ).byteLength;

  return {
    id: artifactId,
    implementation: "flint",
    flintMode,
    artifactKind: "wasm",
    sizeBytes: wasmByteLength,
    hash: artifact.contentHash,
    exports: [...REQUIRED_EXPORTS],
    flintPipeline: {
      pipeline: "flint-son-wasm-two-stage",
      frontend: "son-ir",
      wasmStage: "wasm-ir-optimizer",
      optimization: "release",
      boundsChecks,
      memoryModel: artifact.sonIr?.memoryModel ?? "region-arc-checked-linear",
      sonGraphHash: artifact.sonIr?.graphHash ?? "",
      sonNodeCount: artifact.sonIr?.nodes.length ?? 0,
      sonPassCount: artifact.sonOptimizationReport?.passes.length ?? 0,
    },
    metadata: {
      abi: generated
        ? "generated-esm-over-pointer-length-v1"
        : "pointer-length-native-v1",
      compilerVersion: COMPILER_VERSION,
      loader: generated ? "generated-esm" : "raw-pointer-length",
      nativeKernels: true,
      instancePolicy: "reusable-with-reset",
      resetAbi: "fws_reset-v1",
      rawWasmBytes: wasmByteLength,
      pipeline: "flint-son-wasm-two-stage",
      frontend: "son-ir",
      wasmStage: "wasm-ir-optimizer",
      optimization: "release",
      boundsChecks,
      memoryModel: artifact.sonIr?.memoryModel ?? "region-arc-checked-linear",
      sonGraphHash: artifact.sonIr?.graphHash ?? "",
      sonNodeCount: artifact.sonIr?.nodes.length ?? 0,
      sonPassCount: artifact.sonOptimizationReport?.passes.length ?? 0,
      generatedSourceBytes: generatedSource.byteLength,
      ...(generated
        ? { generatedSourceHash: hashArtifactBytes(generatedSource) }
        : {}),
      stringInputAllocations: generated ? 1 : 3,
      stringOutputAllocations: 1,
      wasmUrl: new URL(`file://${generatedPath}`).href,
      moduleUrl: pathToFileURL(generatedModulePath).href,
    },
  };
}

/**
 * Converts a Uint8Array into a guaranteed ArrayBuffer BufferSource for WebAssembly module compilation.
 *
 * @param bytes - Byte array.
 * @returns An ArrayBuffer containing the byte payload.
 */
function toBufferSource(bytes: Uint8Array): BufferSource {
  const copy = new Uint8Array(bytes.byteLength);
  copy.set(bytes);
  return copy.buffer;
}

/**
 * Compiles Flint source code, validates artifacts, writes files to disk, and returns compiled state.
 *
 * @param source - Flint source code string.
 * @param boundsChecks - Target bounds check enforcement level.
 * @param artifactId - Resolved artifact identifier.
 * @param flintMode - Target Flint mode.
 * @param generated - Whether using generated ESM loader.
 * @returns Combined compiled state and benchmark build artifact.
 * @throws {Error} If compilation fails or produces diagnostics.
 */
function resolveWasmArtifact(
  source: string,
  boundsChecks: "runtime" | "excluded-by-profile",
  artifactId: string,
  flintMode: FlintMode,
  generated: boolean,
): { state: CompiledWasmState; buildArtifact: BuildArtifact } {
  const artifact = compileFlint({
    source,
    fileName: SOURCE_FILE,
    compilerVersion: COMPILER_VERSION,
    optimization: "release",
    boundsChecks,
  });

  if (
    artifact.diagnostics.length > 0 ||
    artifact.wasm === undefined ||
    artifact.manifest === undefined
  ) {
    const details = artifact.diagnostics
      .map((diagnostic) => `${diagnostic.code}: ${diagnostic.message}`)
      .join("; ");
    throw new Error(
      `Native Flint WASM kernels failed to compile${details ? `: ${details}` : "."}`,
    );
  }

  validateFlintWasmArtifact(artifact);
  const wasmBytes = artifact.wasm;
  const generatedSource = encodeUtf8(artifact.esmSource);
  const generatedPath = path.resolve(
    path.dirname(fileURLToPath(import.meta.url)),
    "../../generated/fws/kernels.wasm",
  );
  const generatedModulePath = path.resolve(
    path.dirname(fileURLToPath(import.meta.url)),
    "../../generated/fws/kernels.generated.mjs",
  );

  mkdirSync(path.dirname(generatedPath), { recursive: true });
  writeFileSync(generatedPath, wasmBytes);
  writeFileSync(generatedModulePath, artifact.esmSource);

  const state: CompiledWasmState = {
    artifact,
    wasmBytes,
    module: new WebAssembly.Module(toBufferSource(wasmBytes)),
    generatedModuleUrl: pathToFileURL(generatedModulePath).href,
  };

  const buildArtifact = buildWasmArtifactDescriptor(
    artifactId,
    flintMode,
    boundsChecks,
    generated,
    artifact,
    generatedSource,
    generatedPath,
    generatedModulePath,
  );

  return { state, buildArtifact };
}

/**
 * Type guard verifying that a dynamically imported module satisfies GeneratedFlintModule.
 *
 * @param value - Candidate import value.
 * @returns True if value conforms to the GeneratedFlintModule interface.
 */
function isGeneratedFlintModule(value: unknown): value is GeneratedFlintModule {
  return (
    typeof value === "object" &&
    value !== null &&
    "loadSync" in value &&
    typeof value.loadSync === "function" &&
    "load" in value &&
    typeof value.load === "function"
  );
}

/**
 * Instantiates the WebAssembly module or loads its ESM wrapper.
 *
 * @param state - In-memory compiled state.
 * @param artifact - Build artifact containing content hash.
 * @param generated - Whether to use ESM loader.
 * @param cachedModule - Previously imported ESM module if cached.
 * @returns Instantiated exports and optional cached ESM module.
 * @throws {TypeError} If ESM module or reset exports are missing or have invalid types.
 */
async function instantiateWasmModule(
  state: CompiledWasmState,
  artifact: BuildArtifact,
  generated: boolean,
  cachedModule?: GeneratedFlintModule,
): Promise<{
  instantiation: WasmInstantiationResult;
  updatedGeneratedModule?: GeneratedFlintModule;
}> {
  if (generated) {
    let generatedModule = cachedModule;
    if (generatedModule === undefined) {
      const url = `${state.generatedModuleUrl}?hash=${artifact.hash ?? ""}`;
      const loadedModule: unknown = await import(url);
      if (!isGeneratedFlintModule(loadedModule)) {
        throw new TypeError("Generated Flint module has no loadSync loader.");
      }
      generatedModule = loadedModule;
    }
    const generatedExports = generatedModule.loadSync();
    if (typeof generatedExports.fws_reset !== "function") {
      throw new TypeError(
        "Generated Flint module is missing the fws_reset ABI export.",
      );
    }
    return {
      instantiation: { generatedExports },
      updatedGeneratedModule: generatedModule,
    };
  }

  const rawInstance = new WebAssembly.Instance(state.module, {});
  const preparedExports = asExports(rawInstance.exports);
  return {
    instantiation: { preparedExports },
  };
}

/**
 * Dispatches an input workload through compiler-generated ESM bindings.
 *
 * @param exports - Generated module exports.
 * @param input - Benchmark input payload.
 * @returns Normalized benchmark output.
 */
function executeGeneratedWasmInput(
  exports: GeneratedFlintExports,
  input: BenchmarkInput,
): BenchmarkOutput {
  return withReset(exports, () => {
    if ("multiplier" in input) {
      return normalizeBenchmarkOutput(
        exports.arithmetic_reduce(
          input.n,
          input.multiplier,
          input.offset,
          input.seed,
        ),
      );
    }
    if ("suffix" in input) {
      return normalizeBenchmarkOutput(
        exports.string_transform(
          input.value,
          input.prefix,
          input.suffix,
          input.repeat,
        ),
      );
    }
    const payload = writeGuestBytes(
      exports.memory,
      exports.fws_alloc,
      Uint8Array.from(input.bytes),
    );
    try {
      return normalizeBenchmarkOutput(
        exports.dataset_scan(
          [payload.pointer, payload.length],
          input.threshold,
        ),
      );
    } finally {
      exports.fws_dealloc(payload.pointer, payload.length);
    }
  });
}

/**
 * Dispatches an input workload directly through raw WebAssembly memory and functions.
 *
 * @param exports - Raw WebAssembly instance exports.
 * @param input - Benchmark input payload.
 * @returns Normalized benchmark output.
 */
function executeRawWasmInput(
  exports: FlintExports,
  input: BenchmarkInput,
): BenchmarkOutput {
  return withReset(exports, () => {
    if ("multiplier" in input) {
      return normalizeBenchmarkOutput(
        exports.arithmetic_reduce(
          input.n,
          input.multiplier,
          input.offset,
          input.seed,
        ),
      );
    }
    if ("suffix" in input) {
      const value = writeGuestBytes(
        exports.memory,
        exports.fws_alloc,
        encodeUtf8(input.value),
      );
      const prefix = writeGuestBytes(
        exports.memory,
        exports.fws_alloc,
        encodeUtf8(input.prefix),
      );
      const suffix = writeGuestBytes(
        exports.memory,
        exports.fws_alloc,
        encodeUtf8(input.suffix),
      );
      let output: MemoryRange | undefined;
      try {
        const [pointer, length] = exports.string_transform(
          value.pointer,
          value.length,
          prefix.pointer,
          prefix.length,
          suffix.pointer,
          suffix.length,
          input.repeat,
        );
        output = { pointer, length };
        return normalizeBenchmarkOutput(
          decodeUtf8(readGuestBytes(exports.memory, pointer, length)),
        );
      } finally {
        releaseRanges(exports, [output, value, prefix, suffix]);
      }
    }
    const payload = writeGuestBytes(
      exports.memory,
      exports.fws_alloc,
      Uint8Array.from(input.bytes),
    );
    try {
      return normalizeBenchmarkOutput(
        exports.dataset_scan(payload.pointer, payload.length, input.threshold),
      );
    } finally {
      exports.fws_dealloc(payload.pointer, payload.length);
    }
  });
}

/**
 * Constructs an invocation bridge function to execute workloads on the instantiated module.
 *
 * @param instantiation - Initialized exports (raw or generated).
 * @param generated - Whether using generated ESM loader.
 * @returns Closure executing benchmark workloads.
 */
function createWasmInvocationBridge(
  instantiation: WasmInstantiationResult,
  generated: boolean,
): (input: BenchmarkInput) => BenchmarkOutput {
  if (generated) {
    const exports = assertDefined(
      instantiation.generatedExports,
      "Generated Flint exports were not initialized.",
    );
    return (input: BenchmarkInput) => executeGeneratedWasmInput(exports, input);
  }

  const exports = assertDefined(
    instantiation.preparedExports,
    "Raw Flint exports were not initialized.",
  );
  return (input: BenchmarkInput) => executeRawWasmInput(exports, input);
}

/**
 * Validates that an initialization artifact matches the expected adapter identity and mode.
 *
 * @param artifact - Build artifact to validate.
 * @param expectedId - Expected adapter ID.
 * @param expectedMode - Expected Flint mode.
 * @throws {Error} If artifact attributes do not match expectations.
 */
function validateBuildArtifactMatch(
  artifact: BuildArtifact,
  expectedId: string,
  expectedMode: FlintMode,
): void {
  if (
    artifact.id !== expectedId ||
    artifact.flintMode !== expectedMode ||
    artifact.artifactKind !== "wasm"
  ) {
    throw new Error(
      "Flint WASM adapter received an incompatible build artifact.",
    );
  }
}

/**
 * Extracts preparation metadata for benchmark reports.
 *
 * @param generated - Whether using generated ESM loader.
 * @returns Preparation metadata record.
 */
function extractWasmPreparationMetadata(
  generated: boolean,
): Record<string, string | number | boolean> {
  return {
    modulesCompiled: 1,
    abi: generated
      ? "generated-esm-over-pointer-length-v1"
      : "pointer-length-native-v1",
    nativeKernels: true,
    instancePolicy: "reusable-with-reset",
    resetAbi: "fws_reset-v1",
    stringInputAllocations: generated ? 1 : 3,
    stringOutputAllocations: 1,
  };
}

/**
 * Internal factory for configuring and constructing Flint WebAssembly benchmark adapters.
 *
 * @param source - Flint source code string.
 * @param loader - Loader mode ("raw" or "generated").
 * @param boundsChecks - Bounds checking mode ("runtime" or "excluded-by-profile").
 * @param modeOverride - Optional FlintMode override.
 * @returns Configured RuntimeAdapter instance.
 */
function createFlintWasmAdapterInternal(
  source: string,
  loader: FwsWasmLoader,
  boundsChecks: "runtime" | "excluded-by-profile" = "runtime",
  modeOverride?: FlintMode,
): RuntimeAdapter {
  const generated = loader === "generated";
  const artifactId = resolveArtifactId(modeOverride, generated);
  const flintMode = modeOverride ?? (generated ? "wasm-generated" : "wasm");
  let compiledState: CompiledWasmState | undefined;
  let cachedGeneratedModule: GeneratedFlintModule | undefined;

  return {
    implementation: "flint",
    mode: flintMode,
    adapterId: artifactId,
    async build(): Promise<BuildArtifact> {
      const resolved = resolveWasmArtifact(
        source,
        boundsChecks,
        artifactId,
        flintMode,
        generated,
      );
      compiledState = resolved.state;
      return resolved.buildArtifact;
    },
    async initialize(artifact: BuildArtifact): Promise<InitializedAdapter> {
      validateBuildArtifactMatch(artifact, artifactId, flintMode);
      const state = assertDefined(
        compiledState,
        "Flint WASM adapter must be built before initialization.",
      );
      const { instantiation, updatedGeneratedModule } =
        await instantiateWasmModule(
          state,
          artifact,
          generated,
          cachedGeneratedModule,
        );
      if (updatedGeneratedModule !== undefined) {
        cachedGeneratedModule = updatedGeneratedModule;
      }
      return {
        adapterId: artifactId,
        preparation: extractWasmPreparationMetadata(generated),
        execute: createWasmInvocationBridge(instantiation, generated),
      };
    },
  };
}

/**
 * Creates a benchmark adapter executing native Flint WebAssembly kernels via direct pointer ABI.
 *
 * @param source - Optional Flint source code; defaults to implementations/fws/kernels.flint.
 * @returns Runtime adapter for raw WebAssembly execution.
 */
export function createFlintWasmAdapter(
  source: string = resolveSource(),
): RuntimeAdapter {
  return createFlintWasmAdapterInternal(source, "raw");
}

/**
 * Creates a benchmark adapter executing native Flint WebAssembly kernels via compiler-generated ESM bindings.
 *
 * @param source - Optional Flint source code; defaults to implementations/fws/kernels.flint.
 * @returns Runtime adapter for generated ESM WebAssembly execution.
 */
export function createFlintGeneratedWasmAdapter(
  source: string = resolveSource(),
): RuntimeAdapter {
  return createFlintWasmAdapterInternal(source, "generated");
}

/**
 * Explicitly builds the same SoN + Wasm pipeline with runtime bounds checks
 * excluded by profile. It is used only as a measured comparison and is never
 * the default benchmark artifact.
 *
 * @param source - Optional Flint source code; defaults to implementations/fws/kernels.flint.
 * @returns Runtime adapter for bounds-excluded WebAssembly execution.
 */
export function createFlintExcludedBoundsWasmAdapter(
  source: string = resolveSource(),
): RuntimeAdapter {
  return createFlintWasmAdapterInternal(
    source,
    "raw",
    "excluded-by-profile",
    "wasm-excluded-bounds",
  );
}
